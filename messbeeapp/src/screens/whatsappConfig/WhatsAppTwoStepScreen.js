import React, { useState, useEffect, useCallback } from 'react';
import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  TouchableOpacity,
  TextInput,
  Platform,
  Alert,
  Modal,
  ActivityIndicator,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import * as Clipboard from 'expo-clipboard';
import { StatusBar } from 'expo-status-bar';
import { Ionicons } from '@expo/vector-icons';
import { whatsappConfigService } from '../../services/api';
import { isValidPin } from '../../utils/validation';

export default function WhatsAppTwoStepScreen({ navigation }) {
  const [loading, setLoading] = useState(true);
  const [isProtected, setIsProtected] = useState(false);
  const [showAutoPin, setShowAutoPin] = useState(false);
  const [autoGeneratedPin, setAutoGeneratedPin] = useState('');
  const [phoneNumber, setPhoneNumber] = useState('');

  const loadPinStatus = useCallback(async () => {
    try {
      setLoading(true);
      const res = await whatsappConfigService.getPhoneStatus();
      if (res) {
        setAutoGeneratedPin(res.registrationPin ? String(res.registrationPin) : '');
        setPhoneNumber(res.phoneNumber || '');
        setIsProtected(Boolean(res.connected && (res.phoneStatus === 'ACTIVE' || res.registrationPin)));
      }
    } catch (err) {
      console.warn('loadPinStatus error:', err.message);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    loadPinStatus();
  }, [loadPinStatus]);

  // Change PIN modal state
  const [showChangePinModal, setShowChangePinModal] = useState(false);
  const [currentPin, setCurrentPin] = useState('');
  const [newPin, setNewPin] = useState('');
  const [confirmPin, setConfirmPin] = useState('');
  const [showCurrentPin, setShowCurrentPin] = useState(false);
  const [showNewPin, setShowNewPin] = useState(false);
  const [showConfirmPin, setShowConfirmPin] = useState(false);
  const [updatingPin, setUpdatingPin] = useState(false);

  // Disable Verification modal state
  const [showDisableModal, setShowDisableModal] = useState(false);

  // Bottom Toast
  const [toastMessage, setToastMessage] = useState('');
  const [showToast, setShowToast] = useState(false);

  const displayToast = (msg) => {
    setToastMessage(msg);
    setShowToast(true);
    setTimeout(() => {
      setShowToast(false);
    }, 3500);
  };

  const copyToClipboard = async (text, label) => {
    if (Clipboard?.setStringAsync) {
      await Clipboard.setStringAsync(text);
    }
    Alert.alert('Copied', `${label} copied to clipboard!`);
  };

  const handleUpdatePin = async () => {
    if (!isValidPin(newPin, 6) || !isValidPin(confirmPin, 6)) {
      Alert.alert('Invalid PIN', 'PIN must be exactly 6 numeric digits (0-9).');
      return;
    }
    if (newPin !== confirmPin) {
      Alert.alert('Mismatch', 'New PIN and Confirm PIN do not match.');
      return;
    }

    setUpdatingPin(true);
    try {
      await whatsappConfigService.registerPin(newPin);
      setAutoGeneratedPin(newPin);
      setIsProtected(true);
      setShowChangePinModal(false);
      setCurrentPin('');
      setNewPin('');
      setConfirmPin('');
      displayToast('Verification PIN updated on Meta & saved!');
    } catch (err) {
      const errMsg = err?.response?.data?.message || err?.response?.data?.error || err.message || 'Failed to update PIN.';
      Alert.alert('PIN Update Failed', errMsg);
    } finally {
      setUpdatingPin(false);
    }
  };

  const handleConfirmDisable = async () => {
    try {
      setUpdatingPin(true);
      await whatsappConfigService.deregisterPin();
      setShowDisableModal(false);
      setIsProtected(false);
      displayToast('Two-step verification disabled.');
    } catch (err) {
      setShowDisableModal(false);
      const errMsg = err?.response?.data?.message || err?.response?.data?.error || err.message || 'Failed to disable verification.';
      Alert.alert('Disable Failed', errMsg);
    } finally {
      setUpdatingPin(false);
    }
  };

  const handleEnableVerification = () => {
    setShowChangePinModal(true);
  };

  return (
    <SafeAreaView style={styles.container}>
      <StatusBar style="dark" />

      {/* Header */}
      <View style={styles.header}>
        <View style={styles.headerLeft}>
          <TouchableOpacity
            onPress={() => navigation.goBack()}
            style={styles.backBtn}
            hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }}
          >
            <Ionicons name="chevron-back" size={24} color="#0F172A" />
          </TouchableOpacity>
          <View>
            <Text style={styles.headerTitle}>Two-Step Verification</Text>
            <Text style={styles.headerSubtitle}>Protect your WhatsApp number</Text>
          </View>
        </View>
      </View>

      <ScrollView
        showsVerticalScrollIndicator={false}
        contentContainerStyle={styles.scrollContent}
      >
        {/* Top Hero Banner */}
        <View style={[styles.heroBanner, !isProtected && styles.heroBannerDisabled]}>
          <View style={styles.heroTopRow}>
            <View style={styles.shieldCircle}>
              <Ionicons
                name={isProtected ? 'shield-checkmark-outline' : 'shield-outline'}
                size={22}
                color="#FFFFFF"
              />
            </View>
            <View style={styles.badgesRow}>
              <View style={styles.badgeItem}>
                <View style={[styles.badgeDot, !isProtected && { backgroundColor: '#EF4444' }]} />
                <Text style={styles.badgeText}>{isProtected ? 'Enabled' : 'Disabled'}</Text>
              </View>
              <View style={styles.badgeItem}>
                <View style={styles.badgeDot} />
                <Text style={styles.badgeText}>Registered</Text>
              </View>
            </View>
          </View>

          <Text style={styles.heroTitle}>
            {isProtected ? 'Your number is protected' : 'Verification is turned off'}
          </Text>
          <Text style={styles.heroSubtitle}>
            A 6-digit PIN is required to register this number with WhatsApp.
          </Text>
        </View>

        {/* Card 1: REGISTRATION PIN */}
        <View style={styles.card}>
          <Text style={styles.cardHeaderTitle}>REGISTRATION PIN</Text>
          <Text style={styles.cardSubTitle}>Current secure PIN</Text>

          {/* 6 masked dots */}
          <View style={styles.pinBoxesRow}>
            {[0, 1, 2, 3, 4, 5].map((idx) => (
              <View key={idx} style={styles.pinBox}>
                <View style={styles.pinDot} />
              </View>
            ))}
          </View>

          <TouchableOpacity
            style={styles.changePinBtn}
            onPress={() => setShowChangePinModal(true)}
            activeOpacity={0.8}
          >
            <Ionicons name="pencil-outline" size={16} color="#1E293B" style={{ marginRight: 6 }} />
            <Text style={styles.changePinBtnText}>Change PIN</Text>
          </TouchableOpacity>
        </View>

        {/* Card 2: Auto-Generated Registration PIN */}
        <View style={styles.card}>
          <Text style={styles.fieldLabel}>
            {phoneNumber ? `Registration PIN (${phoneNumber})` : 'Registration PIN'}
          </Text>
          <View style={styles.autoPinBox}>
            <Text style={styles.autoPinValue}>
              {loading
                ? 'Loading...'
                : !autoGeneratedPin
                ? 'Not set yet'
                : showAutoPin
                ? autoGeneratedPin
                : '••••••'}
            </Text>
            <View style={styles.autoPinActions}>
              <TouchableOpacity
                onPress={() => setShowAutoPin(!showAutoPin)}
                style={styles.iconBtn}
                disabled={!autoGeneratedPin}
                hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
              >
                <Ionicons
                  name={showAutoPin ? 'eye-off-outline' : 'eye-outline'}
                  size={17}
                  color="#64748B"
                />
              </TouchableOpacity>
              <TouchableOpacity
                onPress={() => autoGeneratedPin && copyToClipboard(autoGeneratedPin, 'Registration PIN')}
                style={styles.iconBtn}
                disabled={!autoGeneratedPin}
                hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
              >
                <Ionicons name="copy-outline" size={17} color="#64748B" />
              </TouchableOpacity>
            </View>
          </View>

          <Text style={styles.autoPinNote}>
            This PIN was auto-generated when you connected via Embedded Signup. Keep it safe.
          </Text>
        </View>

        {/* Bottom Toggle Button */}
        {isProtected ? (
          <TouchableOpacity
            style={styles.disableBtn}
            onPress={() => setShowDisableModal(true)}
            activeOpacity={0.7}
          >
            <Text style={styles.disableBtnText}>Disable Verification</Text>
          </TouchableOpacity>
        ) : (
          <TouchableOpacity
            style={styles.enableBtn}
            onPress={handleEnableVerification}
            activeOpacity={0.8}
          >
            <Text style={styles.enableBtnText}>Enable Verification</Text>
          </TouchableOpacity>
        )}
      </ScrollView>

      {/* Modal 1: Change 6-digit PIN Bottom Sheet (Image 3 Screen 2) */}
      <Modal
        visible={showChangePinModal}
        transparent
        animationType="slide"
        onRequestClose={() => setShowChangePinModal(false)}
      >
        <View style={styles.modalBackdrop}>
          <View style={styles.modalSheet}>
            <View style={styles.modalHeader}>
              <Text style={styles.modalTitle}>Change 6-digit PIN</Text>
              <TouchableOpacity
                onPress={() => setShowChangePinModal(false)}
                style={styles.closeBtn}
              >
                <Ionicons name="close" size={20} color="#64748B" />
              </TouchableOpacity>
            </View>

            <View style={styles.modalInputs}>
              {/* Current PIN */}
              <View style={styles.inputGroup}>
                <Text style={styles.inputGroupLabel}>Current PIN</Text>
                <View style={styles.inputBox}>
                  <TextInput
                    style={styles.modalInput}
                    value={currentPin}
                    onChangeText={setCurrentPin}
                    placeholder="Enter current 6-digit PIN"
                    placeholderTextColor="#94A3B8"
                    keyboardType="number-pad"
                    maxLength={6}
                    secureTextEntry={!showCurrentPin}
                  />
                  <TouchableOpacity
                    onPress={() => setShowCurrentPin(!showCurrentPin)}
                    style={styles.iconBtn}
                  >
                    <Ionicons
                      name={showCurrentPin ? 'eye-off-outline' : 'eye-outline'}
                      size={17}
                      color="#64748B"
                    />
                  </TouchableOpacity>
                </View>
              </View>

              {/* New 6-digit PIN */}
              <View style={styles.inputGroup}>
                <Text style={styles.inputGroupLabel}>New 6-digit PIN</Text>
                <View style={styles.inputBox}>
                  <TextInput
                    style={styles.modalInput}
                    value={newPin}
                    onChangeText={setNewPin}
                    placeholder="Enter new 6-digit PIN"
                    placeholderTextColor="#94A3B8"
                    keyboardType="number-pad"
                    maxLength={6}
                    secureTextEntry={!showNewPin}
                  />
                  <TouchableOpacity
                    onPress={() => setShowNewPin(!showNewPin)}
                    style={styles.iconBtn}
                  >
                    <Ionicons
                      name={showNewPin ? 'eye-off-outline' : 'eye-outline'}
                      size={17}
                      color="#64748B"
                    />
                  </TouchableOpacity>
                </View>
              </View>

              {/* Confirm New PIN */}
              <View style={styles.inputGroup}>
                <Text style={styles.inputGroupLabel}>Confirm New PIN</Text>
                <View style={styles.inputBox}>
                  <TextInput
                    style={styles.modalInput}
                    value={confirmPin}
                    onChangeText={setConfirmPin}
                    placeholder="Confirm new 6-digit PIN"
                    placeholderTextColor="#94A3B8"
                    keyboardType="number-pad"
                    maxLength={6}
                    secureTextEntry={!showConfirmPin}
                  />
                  <TouchableOpacity
                    onPress={() => setShowConfirmPin(!showConfirmPin)}
                    style={styles.iconBtn}
                  >
                    <Ionicons
                      name={showConfirmPin ? 'eye-off-outline' : 'eye-outline'}
                      size={17}
                      color="#64748B"
                    />
                  </TouchableOpacity>
                </View>
              </View>
            </View>

            <View style={styles.modalActionsRow}>
              <TouchableOpacity
                style={styles.modalCancelBtn}
                onPress={() => setShowChangePinModal(false)}
              >
                <Text style={styles.modalCancelBtnText}>Cancel</Text>
              </TouchableOpacity>

              <TouchableOpacity
                style={styles.modalUpdateBtn}
                onPress={handleUpdatePin}
                disabled={updatingPin}
              >
                {updatingPin ? (
                  <ActivityIndicator size="small" color="#FFFFFF" />
                ) : (
                  <Text style={styles.modalUpdateBtnText}>Update PIN</Text>
                )}
              </TouchableOpacity>
            </View>
          </View>
        </View>
      </Modal>

      {/* Modal 2: Disable Verification Warning Dialog (Image 3 Screen 3) */}
      <Modal
        visible={showDisableModal}
        transparent
        animationType="fade"
        onRequestClose={() => setShowDisableModal(false)}
      >
        <View style={styles.confirmBackdrop}>
          <View style={styles.confirmDialog}>
            <View style={styles.confirmHeader}>
              <Text style={styles.confirmTitle}>Disable verification?</Text>
              <TouchableOpacity onPress={() => setShowDisableModal(false)} style={styles.closeBtn}>
                <Ionicons name="close" size={20} color="#64748B" />
              </TouchableOpacity>
            </View>

            <View style={styles.warningBox}>
              <Ionicons
                name="warning-outline"
                size={20}
                color="#D97706"
                style={{ marginRight: 10, marginTop: 1 }}
              />
              <Text style={styles.warningText}>
                Your number will no longer require a PIN when it is registered again.
              </Text>
            </View>

            <View style={styles.confirmActions}>
              <TouchableOpacity
                style={styles.confirmCancelBtn}
                onPress={() => setShowDisableModal(false)}
              >
                <Text style={styles.confirmCancelText}>Cancel</Text>
              </TouchableOpacity>

              <TouchableOpacity
                style={styles.confirmDisableBtn}
                onPress={handleConfirmDisable}
              >
                <Text style={styles.confirmDisableText}>Disable Verification</Text>
              </TouchableOpacity>
            </View>
          </View>
        </View>
      </Modal>

      {/* Bottom Green Toast Notification (Image 3 Screen 4) */}
      {showToast && (
        <View style={styles.toastContainer}>
          <View style={styles.toastBox}>
            <Ionicons name="checkmark" size={16} color="#FFFFFF" style={{ marginRight: 8 }} />
            <Text style={styles.toastText}>{toastMessage}</Text>
          </View>
        </View>
      )}
    </SafeAreaView>
  );
}

